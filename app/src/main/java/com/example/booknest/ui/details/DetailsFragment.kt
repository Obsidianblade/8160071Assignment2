package com.example.booknest.ui.details

import android.os.Bundle
import android.view.View
import android.widget.TextView
import androidx.fragment.app.Fragment
import androidx.navigation.fragment.findNavController
import androidx.navigation.fragment.navArgs
import com.example.booknest.R
import com.example.booknest.data.model.Book
import com.google.android.material.appbar.MaterialToolbar

/**
 * Shows every property of the selected book, including the full description.
 *
 * The Book arrives as a Safe Args navigation argument (it is @Parcelize), so this screen
 * makes no network request and survives rotation without losing the book. It has nothing
 * to inject and no logic to test, so it needs neither a ViewModel nor @AndroidEntryPoint.
 */
class DetailsFragment : Fragment(R.layout.fragment_details) {

    // DetailsFragmentArgs is generated by Safe Args from the <argument> in nav_graph.xml.
    private val args: DetailsFragmentArgs by navArgs()

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)

        view.findViewById<MaterialToolbar>(R.id.details_toolbar).setNavigationOnClickListener {
            findNavController().navigateUp()
        }
        showBook(view, args.book)
    }

    private fun showBook(view: View, book: Book) {
        view.findViewById<TextView>(R.id.details_book_title).text = book.title
        view.findViewById<TextView>(R.id.details_author).text = book.author
        view.findViewById<TextView>(R.id.details_genre).text = book.genre
        view.findViewById<TextView>(R.id.details_published).text =
            getString(R.string.details_published, book.publicationYear)
        view.findViewById<TextView>(R.id.details_description).text = book.description
    }
}
