package com.example.booknest.ui.login

import android.os.Bundle
import android.view.View
import android.view.inputmethod.EditorInfo
import android.widget.TextView
import androidx.core.view.WindowCompat
import androidx.core.view.WindowInsetsCompat
import androidx.core.view.isVisible
import androidx.core.widget.doAfterTextChanged
import androidx.fragment.app.Fragment
import androidx.fragment.app.viewModels
import androidx.lifecycle.Lifecycle
import androidx.lifecycle.lifecycleScope
import androidx.lifecycle.repeatOnLifecycle
import androidx.navigation.fragment.findNavController
import com.example.booknest.R
import com.example.booknest.ui.toMessageRes
import com.google.android.material.button.MaterialButton
import com.google.android.material.progressindicator.CircularProgressIndicator
import com.google.android.material.textfield.TextInputEditText
import com.google.android.material.textfield.TextInputLayout
import dagger.hilt.android.AndroidEntryPoint
import kotlinx.coroutines.launch

/**
 * Login screen. It forwards user input to [LoginViewModel] and draws whatever
 * [LoginUiState] the ViewModel exposes. It contains no networking or validation logic.
 */
@AndroidEntryPoint
class LoginFragment : Fragment(R.layout.fragment_login) {

    // `by viewModels()` creates the ViewModel once and keeps it across rotation.
    // Because this Fragment is an @AndroidEntryPoint, Hilt builds it with its dependencies.
    private val viewModel: LoginViewModel by viewModels()

    private lateinit var usernameLayout: TextInputLayout
    private lateinit var usernameInput: TextInputEditText
    private lateinit var passwordLayout: TextInputLayout
    private lateinit var passwordInput: TextInputEditText
    private lateinit var errorText: TextView
    private lateinit var loginButton: MaterialButton
    private lateinit var progressIndicator: CircularProgressIndicator

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        bindViews(view)
        setUpListeners()
        observeUiState()
    }

    private fun bindViews(view: View) {
        usernameLayout = view.findViewById(R.id.username_layout)
        usernameInput = view.findViewById(R.id.username_input)
        passwordLayout = view.findViewById(R.id.password_layout)
        passwordInput = view.findViewById(R.id.password_input)
        errorText = view.findViewById(R.id.login_error)
        loginButton = view.findViewById(R.id.login_button)
        progressIndicator = view.findViewById(R.id.login_progress)
    }

    private fun setUpListeners() {
        loginButton.setOnClickListener { submitLogin() }
        // "Done" on the keyboard submits the form too.
        passwordInput.setOnEditorActionListener { _, actionId, _ ->
            if (actionId == EditorInfo.IME_ACTION_DONE) {
                submitLogin()
                true
            } else {
                false
            }
        }
        usernameInput.doAfterTextChanged { viewModel.onUsernameChanged() }
        passwordInput.doAfterTextChanged { viewModel.onPasswordChanged() }
    }

    private fun submitLogin() {
        WindowCompat.getInsetsController(requireActivity().window, requireView())
            .hide(WindowInsetsCompat.Type.ime())
        viewModel.login(
            username = usernameInput.text?.toString().orEmpty(),
            password = passwordInput.text?.toString().orEmpty()
        )
    }

    /**
     * Collects the state only while the screen is visible (STARTED). The collection stops
     * in the background and restarts automatically, avoiding wasted work and leaks.
     */
    private fun observeUiState() {
        viewLifecycleOwner.lifecycleScope.launch {
            viewLifecycleOwner.repeatOnLifecycle(Lifecycle.State.STARTED) {
                viewModel.uiState.collect { state -> render(state) }
            }
        }
    }

    private fun render(state: LoginUiState) {
        progressIndicator.isVisible = state.isLoading
        loginButton.isEnabled = !state.isLoading
        loginButton.setText(if (state.isLoading) R.string.login_in_progress else R.string.login_button)
        usernameInput.isEnabled = !state.isLoading
        passwordInput.isEnabled = !state.isLoading

        usernameLayout.error =
            if (state.isUsernameMissing) getString(R.string.error_username_required) else null
        passwordLayout.error =
            if (state.isPasswordMissing) getString(R.string.error_password_required) else null

        errorText.isVisible = state.error != null
        state.error?.let { errorText.setText(it.toMessageRes()) }

        state.keypass?.let { keypass -> navigateToDashboard(keypass) }
    }

    private fun navigateToDashboard(keypass: String) {
        // LoginFragmentDirections is generated by Safe Args from nav_graph.xml.
        findNavController().navigate(
            LoginFragmentDirections.actionLoginFragmentToDashboardFragment(keypass)
        )
        viewModel.onNavigatedToDashboard()
    }
}
